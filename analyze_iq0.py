#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
analyze_iq0.py -- reverse-engineering analysis of the GKO.IQ0 block.

Scans the compiled model COSIM.m2630opt.Jul1599 for every load/store access
to the 59 named GKO.IQ0.* slots and classifies the block's signals:

  * per-slot access statistics (reads/writes per state bank, L1/L2 phases);
  * input signals  = non-IQ0 slots loaded by cells that WRITE an IQ0 slot;
  * output consumers = blocks that read an IQ0 slot (cells that load it);
  * native-code regions (0x80-byte evaluation cells) that handle IQ0.

Outputs (text, written to stdout unless --json):
  - slot access summary;
  - IQ0 writer-cell regions (candidate ranges for decompile_model.py);
  - per-cell IQ0 writes with the non-IQ0 inputs of the cell;
  - reader blocks per IQ0 signal (which GKO.* blocks consume it).

Usage:
    python3 analyze_iq0.py                 # full report to stdout
    python3 analyze_iq0.py --json          # machine-readable summary
    python3 analyze_iq0.py --decompile OUT # write the decompiled IQ0 cells
                                           # (writer cells + consumer examples)
"""
import argparse
import json
import sys
from collections import defaultdict, Counter

import importlib.util

spec = importlib.util.spec_from_file_location("cosim", "cosim.py")
cosim = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cosim)

spec2 = importlib.util.spec_from_file_location("decompile_model", "decompile_model.py")
decomp_model = importlib.util.module_from_spec(spec2)
spec2.loader.exec_module(decomp_model)

MODEL = "model/COSIM.m2630opt.Jul1599"
PINLIST = "model/pin.list"
BANK_REG = {13: 0, 14: 1, 15: 2, 16: 3, 17: 4, 18: 5, 19: 6, 20: 7}
LOAD_KINDS = {cosim.K_LBZ, cosim.K_LHZ, cosim.K_LHA, cosim.K_LWZ}
STORE_KINDS = {cosim.K_STB, cosim.K_STH, cosim.K_STW}
CELL = 0x80  # evaluation-cell size (patch seams at 0x80-byte strides)


def block_of(name):
    if not name:
        return "?"
    parts = name.split(".")
    return parts[1] if len(parts) > 1 and parts[0] == "GKO" else "?"


def decompile_iq0(cpu, m, iq0, cells, out_path):
    """Write the decompiled native code of the IQ0-handling cells.

    cells: dict cell_addr -> {"ld": [...], "st": [...], "ld_o": [...], "st_o": [...]}
    Emits every 0x80-byte cell that writes an IQ0 slot (the IQ0 output
    logic) plus the exact cells of a few selected consumer clusters, in
    address order, each cell decompiled by decompile_model.Decomp.
    """
    writer_cells = sorted(c for c, d in cells.items() if d["st"])
    # selected consumer (reader-only) clusters: (start, end, label)
    consumer_ranges = [
        (0x235600, 0x235780, "IQ0 -> LE0/LAS/BP0 fan-out (queue status snapshot)"),
        (0x1ec380, 0x1ecb00, "IQ0 -> L2 cache (IQUAD refill / BHT) consumer cluster"),
        (0x1ecc00, 0x1ed700, "IQ0 -> L2 cache (IQUAD refill / BHT) consumer cluster (cont.)"),
        (0x2fea00, 0x2fed00, "IQ0 -> LAS/HA0 fetch-request consumer cluster"),
        (0x300600, 0x300800, "IQ0 -> LAS/HA0 fetch-request consumer cluster (cont.)"),
        (0x300980, 0x300c00, "IQ0 -> LAS/HA0 fetch-request consumer cluster (cont.)"),
        (0x0f1c00, 0x0f2080, "IQ0 -> IT0 I-TLB / BDR snoop consumer cluster"),
    ]
    wanted = set(writer_cells)
    for s, e, _ in consumer_ranges:
        for c in range(s, e, CELL):
            if c in cells and cells[c]["ld"] and not cells[c]["st"]:
                wanted.add(c)
    wanted = sorted(wanted)

    raw = open(MODEL, "rb").read()
    data = decomp_model.patch_model(raw)

    lines = []
    lines.append("=" * 78)
    lines.append("DECOMPILED NATIVE CODE OF THE GKO.IQ0 BLOCK")
    lines.append("model: %s" % MODEL)
    lines.append("generated by: analyze_iq0.py --decompile (decompile_model.py engine)")
    lines.append("=" * 78)
    lines.append("")
    lines.append("Notation (same as decompile_model.py, in English):")
    lines.append("  w[b][off]  -- 1-bit wire in state bank b (r13..r20 -> 0..7);")
    lines.append("                slot = off (>=0) or off+0x10000; named wires print")
    lines.append("                as GKO.<block>... (e.g. GKO.IQ0.IQWF.NAN3.L2).")
    lines.append("  mem32[b][off] <= ...  -- 32-bit state word (stw).")
    lines.append("  [patch slot] nop      -- patch-list word (0x60000000 after load;")
    lines.append("                the 0x80-byte cell seams).")
    lines.append("  rN                    -- untracked register (block input).")
    lines.append("")
    lines.append("Cells that WRITE an IQ0 slot are the IQ0 output logic (they compute")
    lines.append("the IQ0 signals from other blocks' wires); the selected consumer")
    lines.append("clusters show how IQ0 signals drive the L2 cache, the LSU and the")
    lines.append("I-TLB. %d cells total (%d writers + consumers)." % (len(wanted), len(wanted)))
    lines.append("")

    n = 0
    for c in wanted:
        d = cells[c]
        st_names = ", ".join(iq0[s] for s in sorted(d["st"]))
        if d["st"]:
            label = "IQ0 output cell 0x%06x (writes: %s)" % (c, st_names)
        else:
            ld_names = ", ".join(iq0[s] for s in sorted(d["ld"])[:6])
            label = "IQ0 consumer cell 0x%06x (reads: %s%s)" % (
                c, ld_names, " ..." if len(d["ld"]) > 6 else "")
        dec = decomp_model.Decomp(data)
        dec.run(c, c + CELL, label)
        lines.extend(dec.out)
        lines.append("")
        n += 1
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("written:", out_path, "(%d cells, %d lines)" % (n, len(lines)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--decompile", metavar="OUT", default=None,
                    help="write the decompiled IQ0 cells to OUT (Markdown-"
                         "friendly plain text)")
    args = ap.parse_args()

    m = cosim.Model(MODEL, PINLIST)
    cpu = cosim.CPU(m)
    iq0 = {s: n for s, n in m.slot_names.items() if n.startswith("GKO.IQ0.")}

    # ---- collect per-instruction accesses ----
    # slot -> list of (addr, is_load, bank, mnemonic)
    acc = defaultdict(list)
    for ins in cpu.ins:
        a, k = ins[0], ins[1]
        if k not in (LOAD_KINDS | STORE_KINDS):
            continue
        rt, ra, sd = ins[2], ins[3], ins[4]
        if ra not in BANK_REG:
            continue
        slot = sd & 0xFFFF
        if slot not in iq0:
            continue
        acc[slot].append((a, k in LOAD_KINDS, BANK_REG[ra], cosim.MNEM[k]))

    # ---- per-cell (0x80 block) IQ0 access map ----
    # cell -> {'ld': [slots], 'st': [slots], 'ld_other': [slots], 'st_other': [slots]}
    cells = defaultdict(lambda: {"ld": [], "st": [], "ld_o": [], "st_o": []})
    for ins in cpu.ins:
        a, k = ins[0], ins[1]
        if k not in (LOAD_KINDS | STORE_KINDS):
            continue
        rt, ra, sd = ins[2], ins[3], ins[4]
        if ra not in BANK_REG:
            continue
        slot = sd & 0xFFFF
        c = cells[(a >> 7) << 7]
        if slot in iq0:
            (c["ld"] if k in LOAD_KINDS else c["st"]).append(slot)
        else:
            (c["ld_o"] if k in LOAD_KINDS else c["st_o"]).append(slot)

    writer_cells = sorted(c for c, d in cells.items() if d["st"])
    reader_only_cells = sorted(c for c, d in cells.items() if d["ld"] and not d["st"])
    all_cells = sorted(c for c, d in cells.items() if d["ld"] or d["st"])

    # contiguous runs of cells touching IQ0
    runs = []
    for c in all_cells:
        if runs and c == runs[-1][1] + CELL:
            runs[-1] = (runs[-1][0], c)
        else:
            runs.append((c, c))

    out = []
    out.append("=" * 78)
    out.append("GKO.IQ0 block analysis -- %s" % MODEL)
    out.append("=" * 78)

    # ---- 1. slot summary ----
    out.append("\n## 1. Per-slot access summary (59 named signals)")
    out.append("%-42s %6s %6s %-28s %s" % ("signal", "loads", "stores",
                                           "read banks", "write banks"))
    for slot in sorted(iq0):
        name = iq0[slot]
        lst = acc[slot]
        ld = [x for x in lst if x[1]]
        st = [x for x in lst if not x[1]]
        rb = sorted({x[2] for x in ld})
        wb = sorted({x[2] for x in st})
        out.append("%-42s %6d %6d %-28s %s" % (
            name, len(ld), len(st), ",".join(map(str, rb)), ",".join(map(str, wb))))

    # ---- 2. writer cells ----
    out.append("\n## 2. Cells that WRITE IQ0 slots (%d cells)" % len(writer_cells))
    # runs of writer cells
    wruns = []
    for c in writer_cells:
        if wruns and c == wruns[-1][1] + CELL:
            wruns[-1] = (wruns[-1][0], c)
        else:
            wruns.append((c, c))
    for s, e in wruns:
        out.append("  0x%06x..0x%06x  (%d cells)" % (s, e, (e - s) // CELL + 1))

    # ---- 3. inputs of the IQ0 logic ----
    out.append("\n## 3. Non-IQ0 inputs loaded in IQ0-writer cells")
    in_counter = Counter()
    for c in writer_cells:
        for s in cells[c]["ld_o"]:
            in_counter[s] += 1
    # sort by block then count
    by_block = defaultdict(list)
    for s, cnt in in_counter.items():
        by_block[block_of(m.slot_names.get(s))].append((s, cnt))
    for blk in sorted(by_block):
        items = sorted(by_block[blk], key=lambda x: -x[1])
        names = ["%s(%d)" % (m.slot_names.get(s, "slot0x%04x" % s), c) for s, c in items]
        out.append("  [%-4s] %d slots: %s" % (blk, len(items), ", ".join(names)))

    # ---- 4. reader blocks per IQ0 signal ----
    out.append("\n## 4. Consumers: blocks that READ each IQ0 signal")
    # map slot -> cells that load it but do not store it in the same cell
    for slot in sorted(iq0):
        name = iq0[slot]
        reader_cells = [c for c in cells if slot in cells[c]["ld"]]
        # what do the reader cells store (their outputs)?
        st_other = Counter()
        for c in reader_cells:
            for s in cells[c]["st_o"]:
                st_other[m.slot_names.get(s, "")] += 1
            for s in cells[c]["st"]:
                if s != slot:
                    st_other[iq0[s]] += 1
        top = st_other.most_common(6)
        if top:
            out.append("  %-40s <- read in %3d cells; outputs: %s" % (
                name, len(reader_cells),
                ", ".join("%s(%d)" % (n.split(".")[1] if n.startswith("GKO.") else n, c)
                          for n, c in top)))
        else:
            out.append("  %-40s <- read in %3d cells (no stores nearby)" % (
                name, len(reader_cells)))

    # ---- 5. JSON ----
    if args.json:
        data = {
            "slots": {
                iq0[s]: {
                    "slot": s,
                    "loads": len([x for x in acc[s] if x[1]]),
                    "stores": len([x for x in acc[s] if not x[1]]),
                    "read_banks": sorted({x[2] for x in acc[s] if x[1]}),
                    "write_banks": sorted({x[2] for x in acc[s] if not x[1]}),
                }
                for s in iq0
            },
            "writer_cell_runs": [{"start": s, "end": e} for s, e in wruns],
            "input_blocks": {
                blk: [m.slot_names.get(s, "slot0x%04x" % s) for s, _ in
                      sorted(by_block[blk], key=lambda x: -x[1])]
                for blk in by_block
            },
        }
        print(json.dumps(data, indent=1))
        return

    if args.decompile:
        decompile_iq0(cpu, m, iq0, cells, args.decompile)
        return

    print("\n".join(out))


if __name__ == "__main__":
    main()
